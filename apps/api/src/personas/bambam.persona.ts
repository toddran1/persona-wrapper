function expandReferencePhrases(
  terms: string[],
  prefixes: string[] = [],
  additionalPhrases: string[] = [],
): string[] {
  return [
    ...new Set([
      ...additionalPhrases,
      ...prefixes.flatMap((prefix) => terms.map((term) => `${prefix} ${term}`)),
      ...terms,
    ]),
  ];
}

